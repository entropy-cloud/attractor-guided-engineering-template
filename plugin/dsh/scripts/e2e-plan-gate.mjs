#!/usr/bin/env node
/**
 * e2e-plan-gate.mjs — M3-WI13 reinforcement-gate in-process e2e
 * (dsh-plugin plan `docs/plans/dsh-plugin/2026-08-23-1852-3-pre-execute-plan-status-gate.md`
 * Phase 3 Proof; domain adjudication = Phase 3 Decision: IN-PROCESS e2e on
 * the real host tool stack).
 *
 * What this proves (beyond the unit domain): the `tools/pre-execute`
 * subscription mounted by the REAL service module (through the real
 * `test/fixtures/e2e.cordis.yml` composition: tool-fs + fs-local +
 * fs-observation-policy rows) intercepts REAL `write`/`edit` dispatches
 * through the host tool runtime (`ctx.tools.execute`, the public registry
 * pipeline — waterfall → guards → tool body), with run-state fixtures
 * generated by the REAL bundled engine's own run-state writers:
 *
 *   leg 1 DENY   — write `> Plan Status: completed` onto a tracked plan
 *                  whose subflow file shows a terminal failed closure
 *                  (evidence surface, no allow face) → isError result
 *                  carrying the gate reason; file on disk UNCHANGED.
 *   leg 2 ALLOW-F1— same plan, fresh run whose subflow child is
 *                  `status:"running"` (in-flight face) → write succeeds;
 *                  disk now carries the completed line.
 *   leg 3 ALLOW-D3— create-with-completed on a never-tracked plan path
 *                  (no run-state evidence surface) → write succeeds
 *                  (manual-closure posture, plan D3).
 *   leg 4 DENY   — edit-tool status-line rewrite draft→completed on a
 *                  tracked-unclosed plan → isError with the gate reason.
 *
 * Verification scope (recorded in docs/testing/2026/08-23.md): the
 * deterministic event/tool plane only — no model dispatch happens (no stub
 * model needed beyond adapter construction), no mission loop runs. This is
 * a local explicit gate like `verify:e2e` (not CI merge-blocking), zero
 * credentials, zero external network.
 */
import { createServer } from "node:http";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { boot } from "@deepseek-ai/dsh-app-boot";
import { FlowEngine } from "../assets/src/engine.js";

const PLUGIN_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const E2E_FIXTURE = join(PLUGIN_ROOT, "test", "fixtures", "e2e.cordis.yml");

const failures = [];
const check = (ok, label) => {
  console.log(`${ok ? "ok  " : "FAIL"}  ${label}`);
  if (!ok) failures.push(label);
};

/** Real-engine subflow fixture (same stage vocabulary as the unit suite). */
function engineSubflowFixture(root, runId, planPath, stage) {
  const runDir = join(root, "_tmp", runId);
  mkdirSync(runDir, { recursive: true });
  const subflowId = "EXEC_PLANS-1-0";
  const engine = new FlowEngine({ name: "plan-execution", entry: "EXECUTE", steps: {} }, {
    config: { runDir, subflowId },
    vars: { forEachItem: planPath },
  });
  engine.runId = runId;
  engine.missionName = "demo";
  engine._initWorkflow();
  if (stage === "execute" || stage === "failed") {
    engine._wfOpen("EXECUTE", 1);
    engine._wfClose("pass", "completed");
  }
  if (stage === "fastpath") {
    engine._wfOpen("BUILD_VERIFY", 1);
    engine._wfClose("pass", "completed");
  }
  if (stage === "fastpath") engine._finalizeWorkflow("completed");
  if (stage === "failed") engine._finalizeWorkflow("failed");
  return runDir;
}

/**
 * One real tool dispatch through the host registry pipeline. All legs share
 * one REAL host agent (created through `ctx.get('agents')`, never dispatched
 * — only its identity rides the calls): the fs-observation-policy keys
 * read-before-write observations by `exec.agent.session`, and a no-agent
 * direct call "reads freely but cannot satisfy" the overwrite precondition,
 * so the shared live agent mirrors the real engine-spawned-agent shape whose
 * reads and writes land in one observation owner.
 */
let agentHandle = null;
async function dispatchTool(tools, callId, name, args) {
  const agent = agentHandle?.agent;
  return tools.execute({ callId, name, arguments: args, ...(agent ? { agent } : {}), signal: AbortSignal.timeout(30_000) });
}

function resultText(result) {
  return Array.isArray(result?.content)
    ? result.content.filter((b) => b?.type === "text").map((b) => b.text).join("\n")
    : "";
}

async function main() {
  const root = mkdtempSync(join(tmpdir(), "e2e-plan-gate-"));
  const sessionsDir = join(root, "dsh-sessions");
  const dshHome = join(root, "dsh-home");
  mkdirSync(sessionsDir, { recursive: true });
  mkdirSync(dshHome, { recursive: true });
  mkdirSync(join(root, "missions"), { recursive: true });
  writeFileSync(join(root, "missions", "demo.json"), JSON.stringify({
    name: "demo", roadmapPath: "docs/roadmap", plansDir: "docs/plans/demo", flowName: "native-smoke",
  }), "utf8");

  // Adapter-construction stub endpoint (no turns are dispatched in this e2e).
  const stub = createServer((req, res) => { res.writeHead(404); res.end(); });
  await new Promise((r) => stub.listen(0, "127.0.0.1", r));
  const port = stub.address().port;

  process.env.DSH_CWD = root;
  process.env.DSH_SESSION_ROOT = sessionsDir;
  process.env.DSH_HOME = dshHome;
  process.env.DEEPSEEK_API_KEY = "e2e-stub-no-call";
  process.env.DEEPSEEK_BASE_URL = `http://127.0.0.1:${port}`;

  console.log(`[e2e-plan-gate] booting the real cordis runtime (fixture e2e.cordis.yml)…`);
  const ctx = await boot("mdcontrol-gate-e2e", E2E_FIXTURE);
  try {
    const tools = ctx.get("tools");
    if (!tools || typeof tools.execute !== "function") {
      throw new Error("tools registry not reachable at the root realm (ctx.get('tools'))");
    }
    const agents = ctx.get("agents");
    if (!agents || typeof agents.create !== "function") {
      throw new Error("agents service not reachable at the root realm (ctx.get('agents'))");
    }
    agentHandle = await agents.create({ sessionId: "gate-e2e-agent", meta: { cwd: root } });

    /* leg 1 — DENY: tracked plan, terminal failed closure, no face. */
    const planA = join(root, "docs", "plans", "demo", "a.md");
    mkdirSync(join(root, "docs", "plans", "demo"), { recursive: true });
    writeFileSync(planA, "# Plan A\n\n> Plan Status: active\n\nbody\n", "utf8");
    engineSubflowFixture(root, "gate-r1", planA, "failed");
    await dispatchTool(tools, "gate-1-read", "read", { file_path: planA });
    const deniedWrite = await dispatchTool(tools, "gate-1-write", "write", {
      file_path: planA, content: "# Plan A\n\n> Plan Status: completed\n\nbody\n",
    });
    check(deniedWrite.isError === true, "leg 1: denied write is an error result");
    check(/plan-status gate/.test(resultText(deniedWrite)), "leg 1: error text carries the gate reason");
    check(readFileSync(planA, "utf8").includes("> Plan Status: active"), "leg 1: plan file on disk UNCHANGED (still active)");

    /* leg 2 — ALLOW F1: fresh run, in-flight subflow child (status running). */
    const planB = join(root, "docs", "plans", "demo", "b.md");
    writeFileSync(planB, "# Plan B\n\n> Plan Status: active\n\nbody\n", "utf8");
    engineSubflowFixture(root, "gate-r2", planB, "init");
    await dispatchTool(tools, "gate-2-read", "read", { file_path: planB });
    const allowedWrite = await dispatchTool(tools, "gate-2-write", "write", {
      file_path: planB, content: "# Plan B\n\n> Plan Status: completed\n\nbody\n",
    });
    check(allowedWrite.isError !== true, "leg 2: in-flight-faced write succeeds");
    check(readFileSync(planB, "utf8").includes("> Plan Status: completed"), "leg 2: plan file now completed on disk");

    /* leg 3 — ALLOW D3: create-with-completed on a never-tracked path. */
    const planC = join(root, "docs", "plans", "demo", "c.md");
    const created = await dispatchTool(tools, "gate-3-write", "write", {
      file_path: planC, content: "# Plan C\n\n> Plan Status: completed\n\nbody\n",
    });
    check(created.isError !== true, "leg 3: never-tracked create-with-completed succeeds (D3)");
    check(readFileSync(planC, "utf8").includes("> Plan Status: completed"), "leg 3: file created with completed status");

    /* leg 4 — DENY via the edit tool: status-line rewrite on a
       tracked-unclosed plan (different scratch file, same deny fixture). */
    const planD = join(root, "docs", "plans", "demo", "d.md");
    writeFileSync(planD, "# Plan D\n\n> Plan Status: draft\n\nbody\n", "utf8");
    engineSubflowFixture(root, "gate-r4", planD, "failed");
    await dispatchTool(tools, "gate-4-read", "read", { file_path: planD });
    const deniedEdit = await dispatchTool(tools, "gate-4-edit", "edit", {
      file_path: planD, old_string: "> Plan Status: draft", new_string: "> Plan Status: completed",
    });
    check(deniedEdit.isError === true, "leg 4: denied edit is an error result");
    check(/plan-status gate/.test(resultText(deniedEdit)), "leg 4: error text carries the gate reason");
    check(readFileSync(planD, "utf8").includes("> Plan Status: draft"), "leg 4: plan file on disk UNCHANGED (still draft)");
  } finally {
    try { agentHandle?.dispose?.(); } catch { /* best-effort cleanup */ }
    await ctx.fiber.dispose().catch(() => {});
    stub.close();
    rmSync(root, { recursive: true, force: true });
  }

  if (failures.length > 0) {
    console.error(`[e2e-plan-gate] FAIL — ${failures.length} assertion(s):`);
    for (const f of failures) console.error(`  - ${f}`);
    process.exit(1);
  }
  console.log("[e2e-plan-gate] SUMMARY: PASS — real-host tool pipeline deny×2 (write+edit) + allow×2 (F1 in-flight, D3 never-tracked)");
}

main().catch((err) => {
  console.error("[e2e-plan-gate] crashed:", err);
  process.exit(1);
});
