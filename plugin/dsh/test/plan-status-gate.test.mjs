/* ── 4. wiring shape (fake ctx capture) ──────────────────────────────────── */

test("registerPlanStatusGate: subscribes to tools/pre-execute, deny verbatim, allow delegates to next, returns disposer", async () => {
  const root = tmpProject();
  try {
    const plan = writePlan(root, PLAN_REL, "active");
    engineSubflowFixture(root, "r1", plan, "failed");
    let captured = null;
    let disposed = false;
    const fakeCtx = {
      on(name, listener) { assert.equal(name, "tools/pre-execute"); captured = listener; return () => { disposed = true; }; },
    };
    const warns = [];
    const dispose = registerPlanStatusGate(fakeCtx, { warn: (m) => warns.push(m) });
    assert.equal(typeof dispose, "function");

    const denied = await captured({ name: "write", arguments: { file_path: plan, content: "> Plan Status: completed\n" } }, async () => ({ kind: "allow" }));
    assert.equal(denied.kind, "deny");
    assert.match(denied.reason, /plan-status gate/);
    assert.equal(warns.length, 1);

    const passed = await captured({ name: "write", arguments: { file_path: plan, content: "> Plan Status: draft\n" } }, async () => ({ kind: "allow" }));
    assert.deepEqual(passed, { kind: "allow" });

    const noted = [];
    const fakeCtx2 = {
      on(name, listener) { captured = listener; return () => {}; },
    };
    registerPlanStatusGate(fakeCtx2, { info: (m) => noted.push(m) });
    const allowed = await captured(
      { name: "write", arguments: { file_path: join(root, "docs", "plans", "demo", "fresh.md"), content: "> Plan Status: completed\n" } },
      async () => ({ kind: "allow" }),
    );
    assert.deepEqual(allowed, { kind: "allow" });
    assert.equal(noted.length, 1, "D3 observation note logged");

    dispose();
    assert.equal(disposed, true, "returned disposer unsubscribes");
  } finally { rmSync(root, { recursive: true, force: true }); }
});

