/* ── scratch project factory ─────────────────────────────────────────────── */

function tmpProject() {
  return mkdtempSync(join(tmpdir(), "plan-status-gate-"));
}

function writePlan(root, rel, status = "active") {
  const p = join(root, rel);
  mkdirSync(join(p, ".."), { recursive: true });
  writeFileSync(p, `# Plan\n\n> Plan Status: ${status}\n\nbody\n`, "utf8");
  return p;
}

/* ── REAL-engine fixture generation (fixture authenticity rule) ──────────── */

/**
 * Drive the REAL bundled FlowEngine's run-state writers to produce one
 * subflow child file under <root>/_tmp/<runId>/run-state-<subflowId>.json
 * whose forEachItem is the given plan path. Stage vocabulary:
 *   "init"        → _initWorkflow only (the in-flight shape the engine
 *                   persists at child init: forEachItem + status running)
 *   "execute"     → init + one closed EXECUTE step (post-EXECUTE, still
 *                   running — no closure face except F1)
 *   "closure"     → init + closed CLOSURE_AUDIT visit (F2)
 *   "fastpath"    → init + closed BUILD_VERIFY + finalize completed (F3)
 *   "failed"      → init + closed EXECUTE + finalize failed (deny face)
 */
function engineSubflowFixture(root, runId, planPath, stage) {
  const runDir = join(root, "_tmp", runId);
  mkdirSync(runDir, { recursive: true });
  const subflowId = "EXEC_PLANS-1-0";
  const engine = new FlowEngine({ name: "plan-execution", entry: "EXECUTE", steps: {} }, {
    config: { runDir, subflowId },
    vars: { forEachItem: planPath },
  });
  engine.runId = runId;
  engine.missionName = "demo";
  engine._initWorkflow();
  if (stage === "execute" || stage === "failed") {
    engine._wfOpen("EXECUTE", 1);
    engine._wfClose("pass", "completed");
  }
  if (stage === "closure") {
    engine._wfOpen("CLOSURE_AUDIT", 1);
    engine._wfClose("approved", "completed");
  }
  if (stage === "fastpath") {
    engine._wfOpen("BUILD_VERIFY", 1);
    engine._wfClose("pass", "completed");
  }
  if (stage === "fastpath") engine._finalizeWorkflow("completed");
  if (stage === "failed") engine._finalizeWorkflow("failed");
  return join(runDir, `run-state-${subflowId}.json`);
}

/** Counting IO wrapper — pins the zero-disk-read passthrough property. */
function countingIo(io = fsGateIo) {
  const counts = { readTextFile: 0, listDirEntries: 0 };
  return {
    counts,
    readTextFile(p) { counts.readTextFile++; return io.readTextFile(p); },
    listDirEntries(p) { counts.listDirEntries++; return io.listDirEntries(p); },
    isDirectory: (p) => io.isDirectory(p),
    realPath: (p) => io.realPath(p),
  };
}

